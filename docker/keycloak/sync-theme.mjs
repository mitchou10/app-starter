// Copies the design tokens (colors, radius) and the font of the frontend into the Keycloak login theme,
// so that both look the same. Run it after changing frontend/src/style.css:  node docker/keycloak/sync-theme.mjs
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../../', import.meta.url)
const path = (relative) => fileURLToPath(new URL(relative, root))
const resources = 'docker/keycloak/themes/app/login/resources/'

const css = readFileSync(path('frontend/src/style.css'), 'utf8')
const light = css.match(/:root\s*{[^}]*}/)?.[0]
if (!light) throw new Error('No :root block found in frontend/src/style.css')

writeFileSync(
  path(`${resources}css/tokens.css`),
  `/* Generated by docker/keycloak/sync-theme.mjs from frontend/src/style.css: do not edit. */\n${light}\n`,
)
copyFileSync(
  path('frontend/node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2'),
  path(`${resources}fonts/geist.woff2`),
)
console.log('Keycloak theme synced with the frontend')
